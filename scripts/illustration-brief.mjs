// THE ART DIRECTION FOR EVERY MOVEMENT ILLUSTRATION.
//
// One brief, applied to all of them, because ninety-eight pictures only look
// like a set if the thing that varies between them is the movement and
// nothing else.
//
// -------------------------------------------------------------------------
// READ THIS FIRST: THE STYLE NO LONGER COMES FROM THESE WORDS.
//
// Eight rounds were spent describing Ruth's look in prose. Each round fixed
// the thing she named and broke something next to it, because every
// generation re-decides every variable it was not pinned on. The failures
// below are all of that shape.
//
// What finally held was pinning the look to a PICTURE: her own twelve-panel
// reference sheet, uploaded as a reference image, with the prompt reduced to
// the movement and its two positions. Style from the image, anatomy from the
// text. Her verdict on the first run of it: "they are way better than
// anything else we've done."
//
// THE ANCHOR, and nothing should be generated without it:
//   H:\My Drive\Selodia App Project Master Folder\Build Specs\
//     Branding & Assets\Visual Assets\
//     Movement illustration reference - 12 movements - 16 Oct 2026.png
//
// STYLE below is therefore no longer the instruction. It is kept because it
// is an accurate written description of the house style, which is what a
// human illustrator would need, and because the reasoning in these comments
// is the only record of what was tried and why it failed.
//
// DARK MODE IS NOT A REQUIREMENT and the artwork hedges nothing for it. It
// entered as a hedge and was carried forward out of habit; nobody asked for
// it, the app has none, and no store requires it. It also turns out to need
// no hedge: because the body is unfilled and sits at exactly the ground
// cream, one colour replace over the finished file moves body and background
// together. If it ever happens it is a post-processing pass, not a reshoot.
// The feathered book-like edges existed only to serve it and are dropped too.
// -------------------------------------------------------------------------
//
// -------------------------------------------------------------------------
// HOW THIS BRIEF WAS GOT WRONG, which is worth keeping because the mistakes
// were mine and each one had the same shape.
//
// 1. A PAINTING INSTEAD OF A DRAWING. Ruth's reference is a set of FINE LINE
// DRAWINGS: a single even terracotta contour, flat colour in the clothing, and
// watercolour used only as pale washes BEHIND the figure. I read "soft
// editorial watercolour" and briefed a painting, so the body came back
// rendered - modelled volume, shaded flesh, defined colour.
//
// EVERY LATER PROBLEM CAME OUT OF THAT. Once a model is painting a body it has
// to decide that body's size and that body's skin, so it did: "the figure is
// not a neutral body weight, it in an overweight bodyshape. The hair is
// realistic which makes it too specific, less universal. Skin colour is there
// as a caucasian of some type." Three objections, one cause.
//
// The lesson is not "add more rules". A brief full of negatives - no idealised
// physique, no skin colour, no age cues - cannot produce a universal figure,
// because the drawing still has to be SOMETHING and the model will choose. It
// chose a different particular. A flat-filled line drawing has no modelled fat
// to read and no painted flesh to colour.
//
// 2. NEUTRAL BY OMISSION DOES NOT EXIST. Ruth, on her own reference: "they are
// white people sort of, even tho it's just the background." In line art the
// body is normally left unfilled, and on a cream ground that absence reads as
// pale skin. Then on my first fix: "sand is still white people." Every tone on
// the beige-to-brown axis is somebody's skin. The only way out is to leave the
// axis, so the body is filled SAGE - a colour nobody has, which reads as a
// drawn graphic rather than a person with a race.
//
// Chosen from six options she had drawn up. Terracotta was rejected because it
// makes the body the same colour as the line and the arrows, so the accent
// stops meaning anything, and it is close enough to brown to be read as an
// ethnicity anyway. Graphite and blue both add a colour the brand does not
// own. "Outline only" was offered as "completely race-neutral" and is the very
// option she had already disproved.
//
// 3. NOTHING BRIGHTER THAN THE PAPER. The tee came back filled white: "the
// white t-shirt jarrs against the cream, it's not on the brand pallete." Her
// reference leaves the top UNFILLED - the garment is the cream of the ground,
// described by line alone.
//
// 4. THE WASHES WERE VECTOR, NOT PAINT: "the watercolour blobs aren't watery
// and patchy and editorial as the chatgpt ones, more Vecteezy, less premium."
// Real watercolour pools and dries DARKER AT THE EDGE with a patchy, lighter
// centre. The first attempts produced smooth even clouds with soft pale rims,
// which is the exact opposite, and that inversion is why they read as stock
// art. It is a nameable, fixable tell rather than a vague lack of quality.
//
// 5. AND THEN I MOVED THE SKIN PROBLEM INSTEAD OF SOLVING IT. With the body
// safely sage, the leggings were briefed clay-sand - and clay-sand is a flesh
// tone, so the legs came back reading as bare tan skin with green feet. The
// largest coloured area of the figure was back on the beige axis. The rule
// that actually holds is not "the body is sage" but "NO BEIGE ANYWHERE ON THE
// FIGURE, clothing included", which is why the palette paragraph says so in
// those words.
//
// 6. THE WASH IS COMPOSITION, NOT WALLPAPER, and this killed the "three fixed
// circles on every card" idea - which was hers originally, for the sound
// reason that it would hold ninety-eight pictures together as a set. In
// practice a fixed garnish behind every figure is what made them look cheap:
// "the watercolours look just plonked on randomly now, whereas the chatgpt
// ones felt like a considered acompaniment to the figures position and
// movement, not all colours and sized were used each time and it felt muted
// and like it grew from the activity not just some splashes of paint behind
// it."
//
// So the wash answers the movement - low and spreading under a sinking hip,
// rising behind a lift - and the two panels never carry the same arrangement.
// What makes the ninety-eight a set is the LINE and the PALETTE, not an
// identical background.
//
// 7. "UNFILLED" IS NOT A COLOUR THE MODEL CAN PAINT. Saying the tee was "not
// filled at all" kept producing a white t-shirt, because that is what the
// words "t-shirt" and "unfilled" land on together. It only stopped once the
// colour was named positively: the same cream as the ground, or a hair
// warmer, never lighter than what is behind it.
//
// TWO THINGS HER REFERENCE OVERRULED ME ON:
//   - arrows have proper arrowheads. I had banned them.
//   - the figure sits SMALL in the frame, about a third of the panel, with a
//     lot of empty cream. Mine filled the canvas, which is most of why the
//     early ones read as heavy.
// -------------------------------------------------------------------------

/** The standing brief. Identical for every movement. */
// WHAT GOES INTO THE PROMPT, AND WHAT DOES NOT.
//
// Everything above this line is a record of what went wrong and why, written
// for whoever briefs the next movement. It is NOT prompt text. Until 17 October
// it was all one template literal, which meant the string sent to the image
// model carried sentences like "I read three of these as correct and all three
// were wrong" - notes to myself, diluting the actual instructions.
//
// AND NOTHING IMPORTED IT. Checked on 17 October: no file in the repository
// read this one. Every prompt for the first twenty-two illustrations was
// hand-written at the tool call, which is exactly why the same faults kept
// coming back - a lesson written down in a file nobody reads is not a lesson
// the next picture benefits from. STYLE below is now the only place the art
// direction lives, and movementPrompt is the only way to build a prompt.
//
// IT WAS ALSO STALE. The old STYLE described a figure FILLED with flat sage
// green and asked for a "slim curved terracotta arrow" and a "three-quarter
// view" - all three of which Ruth has since rejected. It would have produced
// the wrong picture on the first call.
export const STYLE = `Draw ONE new illustration in EXACTLY the style of the reference image: the same fine terracotta contour line, the same UNFILLED figure where the cream ground shows straight through the body, the same muted sage leggings, the same soft pale watercolour washes behind the figure, the same cream ground, the same restraint and generous empty space. Copy the reference's colours exactly.

LAYOUT: one tall portrait image with two frames STACKED VERTICALLY, the starting pose in the upper frame and the finishing pose in the lower frame, sharing the same cream ground. Neither frame is captioned or titled. No dividing line, no frame, no border. Both frames seen FROM THE SIDE, at the same camera height, at the same scale, with the figure the same size in each.

THE HEAD IS EMPTY, and this is the instruction most often broken. Inside the outline of the head there is NOTHING except ONE short nose line in profile. No eye, no closed eye, no eyelid, no eyelashes. No eyebrow. No mouth, no lips, no smile. No chin line, no jaw line, no cheekbone. NO CHEEK BLUSH: no pink, no warm patch, no colour of any kind inside the head. No shading inside the head at all. A plain smooth oval of bare cream paper, the outline around it, one small SIMPLE bun of hair, and the nose line. That is all.

A blush is not a face detail. It is a skin tone, and it makes the figure a particular person of a particular colour, which is the one thing this style exists to avoid.

BUT THE HAIR STAYS, AND IT IS NOT A FACE DETAIL. Every figure has a small simple bun in warm brown, drawn as a soft shape at the back of the head. NEVER a bald head. This is said separately from the list above because when it was folded into that list the generator read the whole paragraph as "draw nothing on the head" and returned a bald figure, which breaks the set at a glance.

THE FIGURE IS SMALL IN THE FRAME, occupying roughly a third of the frame's height, with generous empty cream all around it. Airy, restrained and spacious. A figure that fills its frame reads as a different book from the rest of the library even when every other rule is kept.

THE BODY IS UNFILLED: the cream paper shows straight through the torso, arms, hands, legs and feet, exactly the same colour as the background. No skin tone anywhere. NO beige, tan, sand, peach or brown appears anywhere on the figure or on its clothing.

CLOTHING, IDENTICAL IN BOTH FRAMES: a loose short-sleeved CREAM tee, untucked in both, never white and never brighter than the ground; full-length SAGE leggings to the ankle; bare feet. When the figure is inverted the tee stays against the body and does not fall over the head. NO CREASE LINES: interior lines describe structure only, such as a hem, a neckline or a sleeve edge. Never folds, wrinkles, gathers or drape lines.

THE WATERCOLOUR WASHES sit BEHIND the figure in BOTH frames, in the reference's colours, never touching or colouring it. Real watercolour on rough paper: uneven patchy pigment, darker dried rims with washed-out centres, irregular organic edges. NOT circles, NOT ovals, NOT smooth gradients, NOT airbrush softness, which read as cheap vector art. ONE wash per frame, TWO AT MOST, AND NEVER MERGING INTO ONE MASS. Each one is roughly the size of her TORSO - the distance from her shoulder to her hip - and no bigger. It sits behind one part of her, where the effort is or where the movement travels, as a quiet mark rather than a cloud she is lying inside. The two frames differ.

MEASURE IT AGAINST HER TORSO, NOT AGAINST HER. "Smaller than the figure" was the rule before and it failed on the first movement drawn lying down, which is obvious in hindsight: a figure on its side is nearly the width of the frame, so "smaller than the figure" permitted a wash the size of a sofa. A bound that moves with the pose is not a bound. The torso is roughly the same size whatever the body is doing.

THE GROUND IS A SOFT SHADOW, NEVER A LINE. Beneath whatever actually touches the floor, lay a soft, pale, slightly blurred shadow following the shape of that contact. Draw NO hard horizontal line anywhere.

A WALL, WHERE ONE IS NEEDED, IS A SINGLE FINE LINE at the RIGHT edge of the frame, drawn in the same place and at the same scale in both frames. One thin quiet vertical contour line in the same pale terracotta as the figure's outline, and nothing more. Do NOT fill it, shade it, colour it in, or give it width, a panel, a block or a shadow of its own. No bricks, no skirting board, no room, no furniture. The wall is the quietest thing in the frame.

EQUIPMENT IS DRAWN ONLY WHERE THE MOVEMENT NEEDS IT, and then as quietly as the wall. A barbell, a dumbbell, a stick, a box, a chair: the same fine terracotta contour line as the figure, unfilled, no logos, no knurling, no weight plates picked out in detail, no texture. It is the thing in her hands or under her feet and nothing more. Never add equipment that was not named - a bodyweight squat does not acquire a dumbbell because squats often have one - and never draw a mat, a rack, a gym, a window or a floor line.

NO ARROW ANYWHERE. No arrow, no curved line, no swoosh, no motion mark.

NOTHING is brighter than the cream paper, and nothing is darker or more saturated than the figure's own outline.

ABSOLUTELY NO TEXT ANYWHERE: no title, no movement name, no labels, no captions, no headings above or beside either frame, no letters, no numbers. Neither frame is named or titled in the picture. The app writes its own words beside the image, so anything written here appears twice.`;

/**
 * Added to any movement where the figure is upside down.
 *
 * Three of the first four handstands came back facing the wrong way, and I
 * passed all three. An inverted body has almost no readable front, so the nose
 * and the bun are not decoration - they are the only evidence in the picture.
 */
export const NOSE_AND_BUN = `WHICH WAY SHE FACES IS DECIDED BY TWO MARKS AND NOTHING ELSE: the NOSE, a single short line in profile, and the BUN, a small simple knot of hair. Without them an upside-down body reads the same either way, because the torso is a tube, the legs are symmetrical and the arms are straight. Draw both exactly where the frames above place them. If the nose and the bun are not where this prompt says, the picture is wrong however good the rest of it is.`;

/**
 * The per-movement half of the prompt. STYLE decides whether a picture is
 * beautiful; this decides whether it is RIGHT, which matters more - "lizard
 * lunge" on its own comes back as something that is not a lizard lunge, and a
 * confidently wrong demonstration is a form fault.
 *
 * `inverted` adds NOSE_AND_BUN. `ruleOut` names the commoner cousin the
 * generator will drift to and forbids it - "THIS IS NOT THE FRONT SPLITS".
 * `connects` states how the finish is reached from the start, for the stacked
 * pair to be one movement rather than two poses.
 */
export function movementPrompt({ name, start, finish, inverted, ruleOut, connects }) {
  const parts = [
    STYLE,
    '',
    `THE MOVEMENT IS A ${name.toUpperCase()}.`,
    '',
    // THE WORDS "START" AND "FINISH" DO NOT APPEAR IN THIS PROMPT AT ALL
    // (Ruth, 20 October 2026: "Text start and finish in drawing").
    //
    // One of the twenty-one came back with START and FINISH painted into the
    // margin, and the brief had said "ABSOLUTELY NO TEXT ANYWHERE" the whole
    // time. The ban was not the problem. THIS WAS: the last thing the generator
    // read, immediately before drawing, was those two words in capitals at the
    // head of the only two lines that described what to draw. A ban five
    // paragraphs earlier loses to a capitalised word in the final line.
    //
    // So the frames are named by WHERE THEY ARE rather than by what they are.
    // Position is what the layout needs to convey, and "upper" is not a word
    // anybody would caption a drawing with.
    `UPPER FRAME: ${start}`,
    '',
    `LOWER FRAME: ${finish}`,
  ];
  if (inverted) parts.push('', NOSE_AND_BUN);
  if (connects) parts.push('', `THE TWO FRAMES MUST CONNECT. ${connects}`);
  if (ruleOut) parts.push('', `THIS IS NOT ${ruleOut.toUpperCase()}. Do not draw one.`);
  return parts.join('\n');
}

