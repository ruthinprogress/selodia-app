// WHAT THE CHAT IS ALLOWED TO KNOW THE LIBRARY HOLDS.
//
//   node scripts/build-movement-catalogue.mjs
//
// Ruth, 18 October 2026, looking at a Handstand Skills plan the chat had just
// written her: "It cant see what the library is planning to hold, illustrations
// wise, or even what it actually holds. Some plans might be half empty because
// of this."
//
// She was right, and the measurement is bleak. Her plan held five movements -
// wrist prep, plank shoulder taps, a pike hold on a box, a chest-to-wall
// handstand hold, kick-up practice - and NOT ONE of them has a clip or a
// drawing. Meanwhile the library holds a complete seven-stage handstand ladder.
// The chat built a handstand plan beside a handstand progression and matched
// none of it, because nothing had ever told it the progression existed.
//
// WHAT THE PROMPT ACTUALLY SAID. The demonstration marks reach the model in
// exactly one place, and it is for plans ALREADY SAVED: each movement is
// tagged [video] or [words only]. That was the 15 October fix, for READING a
// plan back. Nothing covered WRITING one, and illustrations were not mentioned
// anywhere at all. When the chat told her "I can only see which movements have
// a video once a plan is saved", it was describing its own limits accurately.
//
// WHY THIS IS GENERATED INTO A FILE rather than read from the database at
// request time. The static half of the system prompt is cached, and a cached
// block has to be byte-identical from turn to turn. A file also means the
// catalogue is in git, changes only when somebody uploads something, and can be
// checked against the live library by check-movement-catalogue.mjs - which is
// the lesson from earlier today written down: a document nothing verifies goes
// quietly out of date. See scripts/illustration-brief.mjs.

import fs from 'node:fs';
import { createClient } from '@supabase/supabase-js';

const env = {};
for (const line of fs.readFileSync('.env.local', 'utf8').split(/\r?\n/)) {
  const i = line.indexOf('=');
  if (i > 0 && !line.startsWith('#')) {
    env[line.slice(0, i).trim()] = line.slice(i + 1).trim().replace(/^["']|["']$/g, '');
  }
}
const supabase = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, {
  auth: { persistSession: false },
});

const OUT = 'app/lib/movement-catalogue.ts';

const { data: rows, error } = await supabase
  .from('movement_illustrations')
  .select('join_key, progression, stage')
  .order('progression')
  .order('stage');
if (error) throw error;

// Grouped by progression and left in stage order, because the order IS the
// information: a ladder read out of sequence is just a list of exercises.
const byProgression = new Map();
const loose = [];
for (const row of rows) {
  if (!row.progression) {
    loose.push(row.join_key);
    continue;
  }
  if (!byProgression.has(row.progression)) byProgression.set(row.progression, []);
  byProgression.get(row.progression).push(row.join_key);
}

const lines = [];
for (const [progression, names] of byProgression) {
  lines.push(`${progression}, in order: ${names.join('; ')}`);
}
if (loose.length > 0) lines.push(`Not part of a progression: ${loose.join('; ')}`);

const body = lines.map((l) => `- ${l}`).join('\n');

const file = `// GENERATED by scripts/build-movement-catalogue.mjs. Do not edit by hand.
//
// Regenerate after uploading illustrations:
//   node scripts/build-movement-catalogue.mjs
//
// scripts/check-movement-catalogue.mjs fails if this drifts from the library.

/** Every movement with a drawing, grouped by progression and kept in stage order. */
export const DRAWN_MOVEMENTS = \`${body}\`;

/** How many drawings the catalogue above describes. Checked against the database. */
export const DRAWN_COUNT = ${rows.length};
`;

fs.writeFileSync(OUT, file);
console.log(`\n  ${OUT}`);
console.log(`  ${rows.length} drawings, ${byProgression.size} progressions, ${body.length} chars\n`);
for (const [p, names] of byProgression) console.log(`    ${p}: ${names.length}`);
console.log();
